    <h3 class="font-semibold text-brand-ink text-lg">Penutup: Cintai Tubuhmu Sendiri</h3>

    <p>
        Tubuhmu adalah rumah pertamamu. Setiap perubahan yang kamu alami adalah bagian dari
        perjalanan yang unik — tidak perlu dibandingkan dengan siapa pun. Semakin kamu mengenal
        dan menghargai tubuhmu sendiri, semakin percaya diri kamu menjalani masa remaja.
    </p>

    <x-tip-box title="Butuh Teman Cerita?" icon="🤝">
        <p>Orang tua, wali, atau keluarga yang kamu percaya.</p>
        <p>Guru BK (Bimbingan Konseling) di sekolahmu.</p>
        <p>Puskesmas terdekat — banyak yang punya layanan konseling remaja (PKPR/PIK-R).</p>
        <p>Jika mengalami tekanan atau ancaman dalam hubungan, segera bicarakan dengan orang dewasa terpercaya atau layanan perlindungan anak/remaja setempat.</p>
    </x-tip-box>

