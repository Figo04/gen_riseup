    <ul class="list-disc pl-5 space-y-1">
        <li>Remaja putri di Indonesia rata-rata mengonsumsi energi, protein, lemak, dan karbohidrat di bawah angka kecukupan gizi (sekitar &lt;70% energi dan 50% protein dari kebutuhan).</li>
        <li>Rata-rata asupan remaja putri Indonesia: zat besi (Fe) ≈ 2,6 mg dan zinc (Zn) ≈ 2,1 mg — masih jauh dari rekomendasi kecukupan gizi nasional.</li>
        <li>Asupan vitamin C bervariasi cukup lebar antara wilayah urban dan rural (sekitar 72–980 mg).</li>
        <li>Studi lain menunjukkan &gt;80% anak usia 6–16 tahun tidak mencapai kecukupan kalsium, zat besi, zinc, folat, vitamin A, D, dan B12.</li>
