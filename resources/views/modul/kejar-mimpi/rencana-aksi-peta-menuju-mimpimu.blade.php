        <p>Orang tua, wali, atau keluarga yang kamu percaya.</p>
        <p>Layanan konseling kesehatan jiwa nasional Sejiwa: 119 ext. 8 (cek kembali ketersediaan layanan terbaru di daerahmu).</p>
