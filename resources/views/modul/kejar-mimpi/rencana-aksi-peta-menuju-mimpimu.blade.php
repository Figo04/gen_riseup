    <h3 class="font-semibold text-brand-ink text-lg">Kapan Waktu yang Tepat untuk Menikah?</h3>

    <p>
        Tidak ada jawaban tunggal, tapi beberapa hal ini bisa jadi bahan pertimbangan sebelum
        memutuskan menikah:
    </p>

    <ol class="list-decimal pl-5 space-y-1">
        <li>Kesiapan fisik — usia reproduksi yang matang (idealnya 20 tahun ke atas).</li>
        <li>Kesiapan mental &amp; emosional — mampu mengelola konflik dan mengambil keputusan bersama.</li>
        <li>Kesiapan finansial — memiliki penghasilan/rencana ekonomi yang jelas.</li>
        <li>Kesiapan pendidikan — idealnya pendidikan dasar (minimal SMA) sudah selesai.</li>
        <li>Support system — dukungan keluarga dan lingkungan yang sehat.</li>
    </ol>

    <h3 class="font-semibold text-brand-ink text-lg">Penutup: Kamu yang Menentukan Ceritamu</h3>

    <p>
        Menikah bukan hal yang salah — tapi menikah karena tekanan, bukan karena kesiapan diri,
        bisa menutup banyak pintu kesempatan lain dalam hidupmu. Kamu berhak mengejar mimpi,
        menyelesaikan pendidikan, dan menyiapkan diri sebaik mungkin sebelum melangkah ke
        jenjang berikutnya — termasuk pernikahan.
    </p>

    <p>
        Ingat: setiap orang punya "waktu"-nya masing-masing. Fokus membangun dirimu sendiri
        dulu — circle yang sehat, tubuh yang terjaga, dan mimpi yang terus dikejar.
    </p>

